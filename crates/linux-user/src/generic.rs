/// The host number of the generic system call `nr`, `None` when there is none.
pub(crate) fn to_host(nr: u64) -> Option<i64> {
    let n = *GENERIC_TO_X86.get(usize::try_from(nr).ok()?)?;
    (n >= 0).then_some(i64::from(n))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn maps_to_the_host_numbers() {
        assert_eq!(to_host(63), Some(libc::SYS_read));
        assert_eq!(to_host(64), Some(libc::SYS_write));
        assert_eq!(to_host(56), Some(libc::SYS_openat));
        assert_eq!(to_host(79), Some(libc::SYS_newfstatat));
        assert_eq!(to_host(93), Some(libc::SYS_exit));
        assert_eq!(to_host(139), Some(libc::SYS_rt_sigreturn));
        assert_eq!(to_host(220), Some(libc::SYS_clone));
        assert_eq!(to_host(222), Some(libc::SYS_mmap));
        assert_eq!(to_host(258), None);
        assert_eq!(to_host(10_000), None);
    }
}
