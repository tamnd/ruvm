/// The upper bits of a NaN boxed half precision or bf16 value, `gen_nanbox_h()`.
const NANBOX_H: u64 = 0xffff_ffff_ffff_0000;
/// The sign bit of a single precision value.
const SIGN_S: i64 = 1 << 31;

