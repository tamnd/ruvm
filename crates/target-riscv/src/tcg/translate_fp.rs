#[cfg(test)]
mod tests {
    use super::*;
    use ruvm_softfloat::{Float32, Float64, FloatStatus};

    #[test]
    fn fli_tables() {
        let mut st = FloatStatus::default();
        for i in 0..32 {
            let s = FLI_S[i];
            let d = FLI_D[i];
            assert_eq!(s >> 32, 0xffff_ffff, "fli.s {i} is NaN boxed");
            let s = Float32(s as u32);
            let d = Float64(d);
            if i == 31 {
                assert!(s.is_any_nan() && d.is_any_nan());
                assert_eq!(s.0, 0x7fc0_0000);
                assert_eq!(d.0, 0x7ff8_0000_0000_0000);
                continue;
            }
            if i == 1 {
                // The minimum positive normal of each format, checked below.
                continue;
            }
            // Every other entry is exact in single precision and the same value in both
            // tables.
            assert_eq!(s.to_float64(&mut st), d, "entry {i}");
        }
        assert_eq!(st.flags(), 0);
        assert_eq!(FLI_D[0], (-1.0f64).to_bits());
        assert_eq!(FLI_D[1], f64::MIN_POSITIVE.to_bits());
        assert_eq!(FLI_S[1] as u32, f32::MIN_POSITIVE.to_bits());
        assert_eq!(FLI_D[2], 2f64.powi(-16).to_bits());
        assert_eq!(FLI_D[9], 0.3125f64.to_bits());
        assert_eq!(FLI_D[21], 2.5f64.to_bits());
        assert_eq!(FLI_D[29], 65536f64.to_bits());
        assert_eq!(FLI_D[30], f64::INFINITY.to_bits());
        assert_eq!(FLI_S[30] as u32, f32::INFINITY.to_bits());
        // Strictly increasing from entry 2 to +inf.
        for i in 2..30 {
            assert!(f64::from_bits(FLI_D[i]) < f64::from_bits(FLI_D[i + 1]), "entry {i}");
        }
    }

    #[test]
    fn nanbox_constants() {
        assert_eq!(NANBOXED_NAN_S, NANBOX_S | 0x7fc0_0000);
        assert_eq!(FLI_S[31], NANBOXED_NAN_S);
        assert_eq!(SIGN_S, 0x8000_0000);
    }
}
